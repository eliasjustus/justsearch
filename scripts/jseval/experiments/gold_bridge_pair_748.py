#!/usr/bin/env python3
"""748 Phase 2 — the EN/DE matched-pair bridge probe, on gold payloads only.

Tempdoc 748's charter experiment 1 asks whether the zero-lexical-overlap
synonym-descriptor gold design is itself the hard thing (hypothesis (c)) rather
than German (hypothesis (a)). The whole-corpus form of that question needs
assembled cells and a backend. This is the *cheapest* form of it, and it needs
neither: it asks whether the production encoder can match a query to its own
gold document among the OTHER gold documents of the same construction — the
bridge, with the host corpus and the engine both removed.

Because both members' gold sets are generated by the same generator with the
same knobs, differing only in `lang`, the EN-vs-DE comparison is controlled.

Two hygiene steps are applied and reported:
  * `_FILLER` (the English boilerplate leak the 748 rebuild removes) is stripped
    from every payload before encoding, so the DE side is not scored on English
    text it should never have carried.
  * distractor payload documents from the same generation are kept as the
    competitor pool, so "find your own gold among near-identical siblings" is
    the actual task — the hard-negative structure the generator intends.

Usage:
  python gold_bridge_pair_748.py \
      --cell scripts/jseval/781-corpora/en-legal-clerc/1000-verbose --label en-legal-v2 \
      --cell scripts/jseval/707-corpora/de-miracl/1000-verbose      --label de-miracl-v1-defillered \
      --out scripts/jseval/tmp/748/gold-bridge-pair.json
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from encoder_bridge_scale_748 import DEFAULT_MODEL_DIR, Encoder  # noqa: E402


def _filler() -> str:
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    from jseval.corpus_generate import _FILLER

    return _FILLER


def load_cell(cell: Path, filler: str) -> tuple[list[dict], list[dict], dict]:
    docs = [
        json.loads(line)
        for line in (cell / "fabricated-docs.jsonl").read_text("utf-8").splitlines()
        if line.strip()
    ]
    queries = json.loads((cell / "fabricated-queries.json").read_text("utf-8"))
    if isinstance(queries, dict):
        queries = queries.get("queries", [])

    stripped = 0
    for d in docs:
        text = d.get("text") or ""
        if filler in text:
            stripped += 1
            # Remove every repetition, then collapse the whitespace it leaves.
            text = " ".join(text.replace(filler, " ").split())
            d["text"] = text
    stats = {
        "n_docs": len(docs),
        "n_queries": len(queries),
        "docs_with_filler_before": stripped,
        "filler_share_before": round(stripped / max(len(docs), 1), 4),
        "median_chars_after": int(
            np.median([len(d.get("text") or "") for d in docs])
        ),
    }
    return docs, queries, stats


def ndcg_at_k(ranked: list[str], relevant: set[str], k: int = 10) -> float:
    dcg = sum(1.0 / math.log2(i + 2) for i, d in enumerate(ranked[:k]) if d in relevant)
    ideal = sum(1.0 / math.log2(i + 2) for i in range(min(len(relevant), k)))
    return dcg / ideal if ideal else 0.0


def score(
    cell: Path,
    label: str,
    enc: Encoder,
    filler: str,
    batch: int,
    pool_cap: int | None = None,
    seed: int = 748,
) -> dict:
    docs, queries, stats = load_cell(cell, filler)

    # Pool-size control. The two members are generated with different
    # `distractor_ratio` (EN v2 = 0, DE v1 = 5), so their competitor pools differ
    # 100 vs 240. Both `gold_margin` (a max over competitors) and rank depend on
    # pool size, so an uncontrolled EN-vs-DE comparison would confound language
    # with distractor mass. `--pool-cap` keeps every gold document and seeded-
    # subsamples the rest to a common size.
    if pool_cap is not None and len(docs) > pool_cap:
        import random

        gold_ids = {g for q in queries for g in (q.get("evidence_ids") or [])}
        gold = [d for d in docs if d["_id"] in gold_ids]
        rest = [d for d in docs if d["_id"] not in gold_ids]
        random.Random(seed).shuffle(rest)
        docs = gold + rest[: max(0, pool_cap - len(gold))]
        stats["pool_capped_to"] = pool_cap

    ids = [d["_id"] for d in docs]
    texts = [
        ((d.get("title") or "") + "\n" + (d.get("text") or "")).strip() for d in docs
    ]
    dv = enc.encode(texts, batch_size=batch)
    qtexts = [q.get("query") or q.get("text") or "" for q in queries]
    qv = enc.encode(qtexts, batch_size=batch)
    pos = {d: i for i, d in enumerate(ids)}
    sims = qv @ dv.T

    r1, r10, nd, margins, ranks = [], [], [], [], []
    for qi, q in enumerate(queries):
        rel = {g for g in (q.get("evidence_ids") or []) if g in pos}
        if not rel:
            continue
        order = np.argsort(-sims[qi])
        ranked = [ids[j] for j in order]
        r1.append(1.0 if ranked[0] in rel else 0.0)
        r10.append(1.0 if any(d in rel for d in ranked[:10]) else 0.0)
        nd.append(ndcg_at_k(ranked, rel, 10))
        rel_pos = [pos[g] for g in rel]
        best_gold = float(np.max(sims[qi][rel_pos]))
        mask = np.ones(len(ids), dtype=bool)
        mask[rel_pos] = False
        margins.append(best_gold - float(np.max(sims[qi][mask])))
        ranks.append(min(i for i, d in enumerate(ranked) if d in rel) + 1)

    return {
        "label": label,
        "cell": str(cell),
        **stats,
        "n_scored": len(nd),
        "pool_size": len(ids),
        "bridge_p@1": round(float(np.mean(r1)), 4),
        "bridge_recall@10": round(float(np.mean(r10)), 4),
        "bridge_ndcg@10": round(float(np.mean(nd)), 4),
        "gold_margin_mean": round(float(np.mean(margins)), 4),
        "gold_margin_positive_share": round(
            float(np.mean([1.0 if m > 0 else 0.0 for m in margins])), 4
        ),
        "gold_rank_median": float(np.median(ranks)),
        "gold_rank_p90": float(np.percentile(ranks, 90)),
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--cell", action="append", required=True, type=Path)
    ap.add_argument("--label", action="append", required=True)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--model-dir", type=Path, default=DEFAULT_MODEL_DIR)
    ap.add_argument("--provider", choices=("cpu", "cuda"), default="cpu")
    ap.add_argument("--batch-size", type=int, default=8)
    ap.add_argument(
        "--pool-cap",
        type=int,
        default=None,
        help="Cap every cell's competitor pool to this many documents (gold always kept) "
        "so members generated with different distractor_ratio stay comparable.",
    )
    ap.add_argument("--seed", type=int, default=748)
    args = ap.parse_args()
    if len(args.cell) != len(args.label):
        raise SystemExit("--cell and --label must be paired")

    enc = Encoder(args.model_dir, provider=args.provider)
    filler = _filler()
    rows = [
        score(c, lab, enc, filler, args.batch_size, args.pool_cap, args.seed)
        for c, lab in zip(args.cell, args.label)
    ]
    report = {
        "schema": "748-gold-bridge-pair.v1",
        "model_dir": str(args.model_dir),
        "provider": enc.provider,
        "pool_cap": args.pool_cap,
        "note": (
            "Gold-payload-only bridge: no host corpus, no engine, exact cosine. "
            "_FILLER stripped before encoding on every cell."
        ),
        "cells": rows,
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(report, indent=2, ensure_ascii=False), "utf-8")
    print(json.dumps(rows, indent=2, ensure_ascii=False))
    print(f"\nwrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
