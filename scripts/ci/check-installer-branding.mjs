/**
 * Gate for "the NSIS wizard names the version it is installing" (tempdoc 806 B.2, closed by
 * tempdoc 807 R13-F1).
 *
 * Three sandbox rounds in a row reported a wizard that named no version anywhere. 806 routed the
 * version onto the wizard through `bundle.copyright`, which Tauri's generated `installer.nsi`
 * renders as `BrandingText "${COPYRIGHT}"`. Round 13 then found that fix was only half true: the
 * branding strip is drawn on the interior pages and the uninstaller, but MUI's Welcome and Finish
 * pages are full-window and draw no strip, so those two pages still carried nothing. 807 closes
 * them from `installer-hooks.nsh` -- the one installer file this repo owns.
 *
 * Neither half is visible from the repo: the wizard exists only in a built installer, and the
 * template that consumes both inputs is generated by the bundler at build time. So both halves can
 * regress silently -- delete one line of JSON, or one `!define`, and the wizard quietly stops
 * naming the version again with every test still green.
 *
 * This is a static gate on the DECLARED source. It cannot prove a built wizard renders the text;
 * the Sandbox round's page-by-page installer walk is what does that. What it prevents is the
 * declaration silently changing underneath that round.
 */
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

/** Strip NSIS line comments so a commented-out define never counts as present. */
function codeLines(nsh) {
  return nsh
    .split('\n')
    .map((line) => line.replace(/^\s*;.*$/, ''))
    .join('\n');
}

/**
 * `bundle.copyright` is the branding strip's only source, and it must name the version the build
 * actually is -- a strip claiming 0.1.x on a 0.2.0 installer is worse than no strip.
 */
export function checkBrandingSource(tauriConfJson) {
  const failures = [];
  let conf;
  try {
    conf = JSON.parse(tauriConfJson);
  } catch (error) {
    return [`tauri.conf.json does not parse: ${error.message}`];
  }
  const version = conf?.version;
  const copyright = conf?.bundle?.copyright;
  if (typeof version !== 'string' || version.length === 0) {
    failures.push('tauri.conf.json has no top-level "version". sync-version.ps1 owns it.');
  }
  if (typeof copyright !== 'string' || copyright.trim().length === 0) {
    failures.push(
      'tauri.conf.json has no non-empty bundle.copyright. It is rendered as the wizard\'s ' +
        'BrandingText -- the only version-bearing element on the interior pages and the ' +
        'uninstaller. Restore it rather than dropping the version from the wizard.',
    );
    return failures;
  }
  if (typeof version === 'string' && version.length > 0 && !copyright.includes(version)) {
    failures.push(
      `bundle.copyright ("${copyright}") does not contain the bundle version "${version}". The ` +
        `branding strip would name a version the installer is not. sync-version.ps1 derives both ` +
        `from gradle.properties -- run it rather than hand-editing one of them.`,
    );
  }
  return failures;
}

/**
 * The Welcome and Finish pages are full-window (no branding strip), so they carry the version only
 * because `installer-hooks.nsh` defines their text. The bundler's template includes that file
 * before it declares the pages, and MUI takes both texts via `MUI_DEFAULT` (an `!ifndef`), so the
 * defines here win. `MUI_FINISHPAGE_TEXT_LARGE` is not cosmetic: the finish page's text box is 40u
 * without it, which clips the appended line behind the Run / Create-shortcut checkboxes.
 */
export function checkFullPageBranding(nsh) {
  const code = codeLines(nsh);
  const failures = [];
  const required = [
    ['MUI_WELCOMEPAGE_TEXT', 'Welcome'],
    ['MUI_FINISHPAGE_TEXT', 'Finish'],
  ];
  for (const [symbol, page] of required) {
    const define = new RegExp(`^\\s*!define\\s+${symbol}\\s+(.+)$`, 'm').exec(code);
    if (define === null) {
      failures.push(
        `installer-hooks.nsh does not !define ${symbol}. The MUI ${page} page draws no branding ` +
          `strip, so without this define it is a full page of the wizard naming no version ` +
          `(tempdoc 807 R13-F1).`,
      );
      continue;
    }
    if (!define[1].includes('${COPYRIGHT}')) {
      failures.push(
        `installer-hooks.nsh defines ${symbol} without \${COPYRIGHT}: ${define[1].trim()}. The ` +
          `${page} page would render text that does not name the version, or would name a ` +
          `hard-coded one that drifts from gradle.properties.`,
      );
    }
  }
  if (/^\s*!define\s+MUI_FINISHPAGE_TEXT\s+/m.test(code) && !/^\s*!define\s+MUI_FINISHPAGE_TEXT_LARGE\s*$/m.test(code)) {
    failures.push(
      'installer-hooks.nsh overrides MUI_FINISHPAGE_TEXT without !define MUI_FINISHPAGE_TEXT_LARGE. ' +
        'The finish page carries both the Run and the Create-shortcut checkbox, which caps the text ' +
        'box at 40u; the appended branding line is clipped without the larger box.',
    );
  }
  return failures;
}

export function runCheck(root, read = (p) => readFileSync(resolve(root, p), 'utf8')) {
  return [
    ...checkBrandingSource(read('modules/shell/src-tauri/tauri.conf.json')),
    ...checkFullPageBranding(read('modules/shell/src-tauri/nsis/installer-hooks.nsh')),
  ];
}

const invokedDirectly =
  process.argv[1] && import.meta.url.endsWith(process.argv[1].replace(/\\/g, '/').split('/').pop());
if (invokedDirectly) {
  const failures = runCheck(process.cwd());
  if (failures.length > 0) {
    console.error(`installer-branding gate FAILED (${failures.length}):`);
    for (const failure of failures) console.error(`  - ${failure}`);
    process.exit(1);
  }
  console.log(
    'installer-branding gate OK - bundle.copyright names the bundle version, and both MUI ' +
      'full pages (Welcome, Finish) declare version-bearing text (tempdoc 807 R13-F1).',
  );
}
